// The text for `key` in language `l`, {0} … filled in by `args`. A key
// missing in English falls back to German, an unknown one shows itself.
function tr(l, key, args) {
  var table = texts[l] || texts.de
  var text = key in table ? table[key] : key in texts.de ? texts.de[key] : key
  for (var i = 0; i < (args || []).length; i++) text = text.split("{" + i + "}").join(String(args[i]))
  return text
}

// tl(l, key, a, b …): the same with the arguments one by one.
function tl(l, key) { return tr(l, key, Array.prototype.slice.call(arguments, 2)) }

function hasIn(l, key) { return key in (texts[l] || texts.de) }
