// Every text the island shows, in German and English. tl(lang, "key", a, b)
// puts its arguments in for {0}, {1} … The scripts in bin/ keep theirs in
// lib/texts.py. Which language: "language" in config.json ("auto", "de",
// "en"); automatic follows Omarchy's choice (omarchy language, Omarchy 4.5:
// the code in ~/.config/omarchy/language), without one LC_ALL, LC_MESSAGES,
// LANG (the first one set), German for de*, English for everything else. No language is kept in
// here: Quickshell can give each importer its own copy of a library, so the
// language (Theme.lang) is passed to every function that makes text, which
// also makes the bindings follow a change. Pure functions, tested in Node.

var languages = ["de", "en"]

function pickLanguage(setting, env, omarchy) {
  if (languages.indexOf(setting) !== -1) return setting
  // A code as Omarchy's I18n.languageCode takes it ("de", "pt-BR").
  var code = String(omarchy || "").trim()
  if (/^[a-z]{2,3}(-[A-Za-z]{2})?$/.test(code)) return /^de(-|$)/.test(code) ? "de" : "en"
  var vars = env || []
  for (var i = 0; i < vars.length; i++) {
    var v = String(vars[i] || "")
    if (v) return /^de([_.@-]|$)/i.test(v) ? "de" : "en"
  }
  return "en"
}

